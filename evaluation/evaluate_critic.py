"""
Evaluate the live Critic Agent using the RCA generated by the live
Root Cause Agent.

Rate-limit failures are retried and are never counted as critic
PASS, REWORK, or ERROR results.
"""

import time

from evaluation.benchmark import get_benchmark_cases
from evaluation.evidence_builder import build_evidence
from agents.root_cause_agent import root_cause_agent_node
from agents.critic_agent import critic_agent_node


MAX_RETRIES = 5
DEFAULT_RETRY_SECONDS = 3


def is_rate_limit_error(exc):
    """Return True when an exception appears to be a rate-limit error."""
    text = str(exc).lower()

    return (
        "429" in text
        or "rate limit" in text
        or "rate_limit_exceeded" in text
        or "tokens per minute" in text
    )


def get_retry_seconds(exc):
    """
    Extract the retry delay from a rate-limit error when possible.

    Falls back to a conservative delay when the API does not provide
    a usable retry value.
    """
    text = str(exc)

    marker = "try again in "

    if marker in text:
        remaining = text.split(marker, 1)[1]

        number = ""

        for char in remaining:
            if char.isdigit() or char == ".":
                number += char
            else:
                break

        try:
            return max(float(number), DEFAULT_RETRY_SECONDS)
        except ValueError:
            pass

    return DEFAULT_RETRY_SECONDS


def call_with_retry(function, state):
    """
    Execute an LLM-backed agent with rate-limit retries.

    Returns:
        Agent result.

    Raises:
        Exception: if the operation fails for a non-rate-limit reason
        or remains rate-limited after all retries.
    """

    for attempt in range(MAX_RETRIES + 1):
        try:
            return function(state)

        except Exception as exc:
            if not is_rate_limit_error(exc):
                raise

            if attempt >= MAX_RETRIES:
                raise

            wait_seconds = get_retry_seconds(exc)

            print(
                f"\nRate limit reached. "
                f"Waiting {wait_seconds:.1f}s before retry "
                f"({attempt + 1}/{MAX_RETRIES})..."
            )

            time.sleep(wait_seconds)

    raise RuntimeError("Unexpected retry state.")


def evaluate_case(case):
    """Run RCA first, then run the live Critic Agent."""

    state = build_evidence(case["incident_id"])

    rca_result = call_with_retry(
        root_cause_agent_node,
        state,
    )

    state.update(rca_result)

    critic_result = call_with_retry(
        critic_agent_node,
        state,
    )

    verdict = str(
        critic_result.get(
            "critic_verdict",
            "",
        )
    ).upper()

    confidence = critic_result.get(
        "critic_confidence",
        0.0,
    )

    return {
        "incident_id": case["incident_id"],
        "expected_rca": case["expected_rca_category"],
        "predicted_root_cause": rca_result.get(
            "root_cause",
            "",
        ),
        "rca_confidence": rca_result.get(
            "confidence",
            0.0,
        ),
        "critic_verdict": verdict,
        "critic_confidence": confidence,
        "confidence_valid": critic_result.get(
            "critic_confidence_valid",
            False,
        ),
        "critic_feedback": critic_result.get(
            "critic_feedback",
            "",
        ),
        "missing_evidence": critic_result.get(
            "critic_missing_evidence",
            [],
        ),
        "contradictory_evidence": critic_result.get(
            "critic_contradictory_evidence",
            [],
        ),
    }


def main():
    cases = get_benchmark_cases()

    results = []
    api_failures = []

    print("=" * 70)
    print("AI SOFTWARE INCIDENT COMMANDER - CRITIC EVALUATION")
    print("=" * 70)

    for case in cases:
        print(f"\nEvaluating {case['incident_id']}...")

        try:
            result = evaluate_case(case)
            results.append(result)

            print("\nROOT CAUSE:")
            print(result["predicted_root_cause"])

            print("\nEXPECTED RCA:")
            print(result["expected_rca"])

            print("\nRCA CONFIDENCE:")
            print(f"{result['rca_confidence']:.2%}")

            print("\nCRITIC VERDICT:")
            print(result["critic_verdict"])

            print("\nCRITIC CONFIDENCE:")
            print(f"{result['critic_confidence']:.2%}")

            print("\nCONFIDENCE VALID:")
            print(result["confidence_valid"])

            if result["missing_evidence"]:
                print("\nMISSING EVIDENCE:")
                print(result["missing_evidence"])

            if result["contradictory_evidence"]:
                print("\nCONTRADICTORY EVIDENCE:")
                print(result["contradictory_evidence"])

            if result["critic_feedback"]:
                print("\nCRITIC FEEDBACK:")
                print(result["critic_feedback"])

        except Exception as exc:
            api_failures.append(
                {
                    "incident_id": case["incident_id"],
                    "error": str(exc),
                }
            )

            print(
                f"\nEVALUATION ERROR: {exc}"
            )

    print("\n" + "=" * 70)
    print("CRITIC EVALUATION SUMMARY")
    print("=" * 70)

    if results:
        pass_count = sum(
            result["critic_verdict"] == "PASS"
            for result in results
        )

        rework_count = sum(
            result["critic_verdict"] == "REWORK"
            for result in results
        )

        error_count = sum(
            result["critic_verdict"] == "ERROR"
            for result in results
        )

        valid_confidence_count = sum(
            result["confidence_valid"]
            for result in results
        )

        total = len(results)

        pass_rate = pass_count / total

        average_confidence = (
            sum(
                result["critic_confidence"]
                for result in results
            )
            / total
        )

        confidence_valid_rate = (
            valid_confidence_count / total
        )

        print(f"Cases successfully evaluated : {total}")
        print(f"PASS                         : {pass_count}")
        print(f"REWORK                       : {rework_count}")
        print(f"ERROR                        : {error_count}")
        print(
            f"Critic pass rate             : "
            f"{pass_rate:.2%}"
        )
        print(
            f"Average critic confidence    : "
            f"{average_confidence:.2%}"
        )
        print(
            f"Confidence valid rate        : "
            f"{confidence_valid_rate:.2%}"
        )

    else:
        print("No successful critic evaluations.")

    print(
        f"API/evaluation failures      : "
        f"{len(api_failures)}"
    )

    if api_failures:
        print("\nFAILED CASES:")

        for failure in api_failures:
            print(
                f"- {failure['incident_id']}: "
                f"{failure['error']}"
            )

    print("=" * 70)


if __name__ == "__main__":
    main()